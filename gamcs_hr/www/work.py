"""Entry page of the employee and manager app (Vue SPA built from frontend/).

work.html is generated by the frontend build (a copy of the built index.html) and is
not committed; see docs/decisions/0007-work-app-build-output.md.
"""

import frappe
from frappe.boot import load_translations
from frappe.utils.jinja_globals import is_rtl

from gamcs_hr.work_app.api import build_context

no_cache = 1


def get_context(context):
	if frappe.session.user == "Guest":
		frappe.local.flags.redirect_location = "/login?redirect-to=" + frappe.utils.quote(
			frappe.local.request.full_path.rstrip("?")
		)
		raise frappe.Redirect

	csrf_token = frappe.sessions.get_csrf_token()
	frappe.db.commit()  # persist the csrf token on the session (same as hrms's /hrms page)
	context.csrf_token = csrf_token
	context.site_name = frappe.local.site
	context.boot_json = boot_json(get_boot())
	return context


def boot_json(boot: dict) -> str:
	"""JSON for a <script type="application/json"> tag: `<` escaped so it cannot close it."""
	return frappe.as_json(boot, indent=None).replace("<", "\\u003c")


def get_boot() -> dict:
	boot = frappe._dict(
		site_name=frappe.local.site,
		socketio_port=frappe.conf.get("socketio_port"),
		lang=str(frappe.local.lang),
		layout_direction="rtl" if is_rtl() else "ltr",
		gamcs=build_context(frappe.session.user),
	)
	load_translations(boot)
	return boot
